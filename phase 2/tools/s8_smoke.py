"""S8 · Smoke simulation (template + real simulator, no LLM).

usage: python3 s8_smoke.py <handoff> <rtl_root> <out_dir>
 1 builds smoke_tb.sv from the Phase 1 golden vectors (IN-16) plus three fixed cases:
   Reset restores the D-007 values, both invalid codes return 0 and change nothing
   (D-009), display() runs on all three ALU classes
 2 verilator --binary, then runs the executable
 3 parses one PASS/FAIL line per case
writes: <out_dir>/smoke_tb.sv, build.log, smoke_log.txt, smoke_result.json
This is a build-and-basic-behaviour gate, not verification (that is Phase 3).
"""
import json, re, subprocess, sys
from pathlib import Path

h = json.loads(Path(sys.argv[1]).read_text())
root, out = Path(sys.argv[2]).resolve(), Path(sys.argv[3]).resolve()
out.mkdir(parents=True, exist_ok=True)


def lit(v):  # exact 32-bit pattern; avoids the -2147483648 literal pitfall
    return f"int'(32'h{v & 0xFFFFFFFF:08X})"


T = ["// Smoke test generated by S8 from the Phase 1 golden vectors. Do not edit by hand.",
     "module smoke_tb;", "  import cpu_pkg::*;", "", "  CPU cpu;", "  int r, pass_n = 0, fail_n = 0;",
     "  bit c_before;", "",
     "  task automatic check(string id, string what, int got, int exp);",
     "    if (got === exp) begin pass_n++; $display(\"PASS %s %s = %0d\", id, what, got); end",
     "    else begin fail_n++; $display(\"FAIL %s %s: got %0d expected %0d\", id, what, got, exp); end",
     "  endtask", "", "  initial begin", "    cpu = new();"]
for g in h["golden_vectors"]:
    T += [f"    // {g['id']} {g['op']} A={g['a']} B={g['b']} carry_in={g['carry_in']} ({g['note']})",
          f"    cpu.a_alu.set_carry(1'b{g['carry_in']});",
          f"    r = cpu.Calc({lit(g['a'])}, {lit(g['b'])}, {g['op']});",
          f"    check(\"{g['id']}\", \"result\", r, {lit(g['expect'])});",
          f"    check(\"{g['id']}\", \"carry\", int'(cpu.a_alu.get_carry()), "
          f"{g['expect_carry'] if g['expect_carry'] is not None else g['carry_in']});"]
T += ["    // SM-RESET: put non-default state in both ALUs, then Reset (FR-009, D-007, D-008)",
      "    void'(cpu.Calc(5, 7, OP_ADD)); void'(cpu.Calc(5, 7, OP_XOR)); cpu.a_alu.set_carry(1'b1);",
      "    cpu.Reset();",
      "    foreach ({cpu.l_alu, cpu.a_alu}[i]) ;",
      "    check(\"SM-RESET\", \"a_alu.operand_A\", cpu.a_alu.operand_A, 0);",
      "    check(\"SM-RESET\", \"a_alu.operand_B\", cpu.a_alu.operand_B, 0);",
      "    check(\"SM-RESET\", \"a_alu.alu_op\", int'(cpu.a_alu.alu_op), int'(OP_SEL_B));",
      "    check(\"SM-RESET\", \"a_alu.alu_result\", cpu.a_alu.alu_result, 0);",
      "    check(\"SM-RESET\", \"a_alu.carry\", int'(cpu.a_alu.get_carry()), 0);",
      "    check(\"SM-RESET\", \"l_alu.operand_A\", cpu.l_alu.operand_A, 0);",
      "    check(\"SM-RESET\", \"l_alu.operand_B\", cpu.l_alu.operand_B, 0);",
      "    check(\"SM-RESET\", \"l_alu.alu_op\", int'(cpu.l_alu.alu_op), int'(OP_SEL_B));",
      "    check(\"SM-RESET\", \"l_alu.alu_result\", cpu.l_alu.alu_result, 0);"]
for code in ("4'b1110", "4'b1111"):
    sid = "SM-INV-" + code[-4:]
    T += [f"    // {sid}: invalid code returns 0 and changes no ALU state (D-009); expect one $error line",
          "    void'(cpu.Calc(9, 4, OP_SUB)); void'(cpu.Calc(12, 10, OP_AND)); c_before = cpu.a_alu.get_carry();",
          f"    r = cpu.Calc(1, 2, alu_op_t'({code}));",
          f"    check(\"{sid}\", \"result\", r, 0);",
          f"    check(\"{sid}\", \"a_alu.alu_result unchanged\", cpu.a_alu.alu_result, 5);",
          f"    check(\"{sid}\", \"l_alu.alu_result unchanged\", cpu.l_alu.alu_result, 8);",
          f"    check(\"{sid}\", \"a_alu.carry unchanged\", int'(cpu.a_alu.get_carry()), int'(c_before));"]
T += ["    // SM-DISPLAY: display() runs on every ALU class (FR-005, D-010); output is printed, not compared",
      "    begin base_alu b = new(); b.display(); end",
      "    cpu.l_alu.display();", "    cpu.a_alu.display();",
      "    $display(\"SUMMARY pass=%0d fail=%0d\", pass_n, fail_n);", "    $finish;", "  end", "endmodule", ""]
T = [t for t in T if "foreach" not in t]
(out / "smoke_tb.sv").write_text("\n".join(T))

obj = out / "obj_dir"
b = subprocess.run(["verilator", "--binary", "-Wno-fatal", "-f", "files.f", str(out / "smoke_tb.sv"),
                    "--top-module", "smoke_tb", "-Mdir", str(obj), "-o", "smoke"],
                   cwd=root, capture_output=True, text=True)
(out / "build.log").write_text(b.stdout + b.stderr)
res = {"built": b.returncode == 0, "cases": {}, "errors_reported": 0}
if b.returncode == 0:
    r = subprocess.run([str(obj / "smoke"), "+verilator+error+limit+1000"], cwd=root,
                       capture_output=True, text=True)
    log = r.stdout + r.stderr
    (out / "smoke_log.txt").write_text(log)
    for m in re.finditer(r"^(PASS|FAIL) (\S+) (.*)$", log, re.M):
        res["cases"].setdefault(m[2], []).append({"status": m[1], "detail": m[3]})
    res["errors_reported"] = len(re.findall(r"%Error", log))
    res["summary"] = re.search(r"SUMMARY .*", log)[0] if re.search(r"SUMMARY .*", log) else None
    res["display_lines"] = re.findall(r"^\[.*\] op=.*$", log, re.M)
per = {k: "pass" if all(c["status"] == "PASS" for c in v) else "fail" for k, v in res["cases"].items()}
res["per_case"] = per
res["result"] = "pass" if res["built"] and per and all(v == "pass" for v in per.values()) \
    and res["errors_reported"] == 2 else "fail"
res["expected_errors"] = "2 (one per invalid code, from CPU.Calc)"
(out / "smoke_result.json").write_text(json.dumps(res, indent=1))
subprocess.run(["rm", "-rf", str(obj)])
print(res["result"], res.get("summary"), "errors:", res["errors_reported"], "built:", res["built"])
